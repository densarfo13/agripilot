#!/usr/bin/env node
/**
 * check-i18n-coverage.mjs
 *
 * CI guard — verifies translation coverage for Farroway's
 * **active launch languages**: English, Twi (tw), Hindi (hi).
 *
 *   node scripts/ci/check-i18n-coverage.mjs
 *     → 0 when every required domain passes the threshold; 1 otherwise.
 *
 * Post column-split refactor: this guard reads the per-locale
 * column files under src/i18n/columns/T-{locale}.js (the canonical
 * translation source) plus src/i18n/hi.js (a flat single-locale
 * pack still merged via mergePacks at runtime).
 *
 * Twi coverage is derived from T-tw.js (the canonical Twi column)
 * instead of inline `tw:` slots inside translations.js, which no
 * longer exist after the column-split.
 *
 * Active launch languages are listed in LAUNCH_LANGUAGES below.
 * English (the source language) is always present, so it isn't
 * gated separately — every key that exists at all has an `en` slot
 * by construction.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');

const COL_DIR = path.join(ROOT, 'src/i18n/columns');
const HI_FILE = path.join(ROOT, 'src/i18n/hi.js');

// Active launch languages (per i18n upgrade spec). Adding a code
// here extends the guard automatically; no other change required.
const LAUNCH_LANGUAGES = ['en', 'tw', 'hi'];

// Fix 3 — production-stability hardening: enforce 95% across every
// high-risk domain. The build fails when any target language drops
// below the floor, blocking deploys with mixed-language regressions.
const DOMAINS = [
  { name: 'insight.',   threshold: 0.95 },
  { name: 'econ.',      threshold: 0.95 },
  { name: 'rainfall.',  threshold: 0.95 },
  { name: 'seasonal.',  threshold: 0.95 },
  { name: 'topCrops.',  threshold: 0.95 },
];

/**
 * Load a column dict from src/i18n/columns/T-{lang}.js as a Set of
 * its keys. The columns are auto-generated by split-translations.mjs;
 * dynamic import is the simplest way to read them without re-parsing.
 */
async function loadColumnKeys(lang) {
  const p = path.join(COL_DIR, `T-${lang}.js`);
  if (!fs.existsSync(p)) return null;
  const mod = await import(pathToFileURL(p).href);
  const dict = mod.default || mod;
  if (!dict || typeof dict !== 'object') return null;
  return new Set(Object.keys(dict));
}

/**
 * Legacy: the standalone hi.js flat-pack is `const HI = { 'key': 'str' }`.
 * Parsed via regex because the canonical hi column T-hi.js is loaded
 * separately above and we want the keys defined HERE specifically.
 */
function extractKeysFromFlatPack(text) {
  const keys = new Set();
  const re = /^\s*'([a-zA-Z][\w.]+)'\s*:/gm;
  let m;
  while ((m = re.exec(text))) keys.add(m[1]);
  return keys;
}

async function main() {
  // English column = canonical key set ("what keys exist at all").
  const en = await loadColumnKeys('en');
  if (!en) {
    console.error('✗ i18n-coverage: missing src/i18n/columns/T-en.js');
    process.exit(1);
  }

  // Twi canonical column.
  const tw = await loadColumnKeys('tw');
  if (!tw) {
    console.error('✗ i18n-coverage: missing src/i18n/columns/T-tw.js');
    process.exit(1);
  }

  // Hindi: union of the canonical column AND the legacy hi.js pack
  // (still merged at runtime — keys exclusive to either source are
  // visible in the live app).
  const hiCol = await loadColumnKeys('hi');
  if (!hiCol) {
    console.error('✗ i18n-coverage: missing src/i18n/columns/T-hi.js');
    process.exit(1);
  }
  let hi = new Set(hiCol);
  if (fs.existsSync(HI_FILE)) {
    const extra = extractKeysFromFlatPack(fs.readFileSync(HI_FILE, 'utf8'));
    for (const k of extra) hi.add(k);
  }

  const langSets = { en, hi, tw };
  let failed = false;

  for (const lang of LAUNCH_LANGUAGES) {
    if (lang === 'en') {
      console.log(`(en — source language; coverage trivially 100%)`);
      continue;
    }
    const set = langSets[lang];
    if (!set) {
      console.error(`✗ i18n-coverage: no extractor wired for "${lang}"`);
      failed = true;
      continue;
    }
    for (const d of DOMAINS) {
      let enCount = 0, langCount = 0;
      for (const k of en) if (k.startsWith(d.name)) enCount += 1;
      for (const k of set) if (k.startsWith(d.name)) langCount += 1;
      const ratio = enCount > 0 ? langCount / enCount : 1;
      const ok = enCount === 0 || ratio >= d.threshold;
      const mark = ok ? '✓' : '✗';
      const pct = (ratio * 100).toFixed(0);
      console.log(`${mark} ${d.name}*  ${lang}/en = ${langCount}/${enCount}  (${pct}%, required ${(d.threshold * 100).toFixed(0)}%)`);
      if (!ok) failed = true;
    }
  }

  if (failed) {
    console.error('');
    console.error('Fix: add missing keys for the failing language × domain combos.');
    console.error('  • Hindi gaps  → src/i18n/columns/T-hi.js or src/i18n/hi.js');
    console.error('  • Twi gaps    → src/i18n/columns/T-tw.js');
    console.error('Launch-language farmers currently see English for these screens.');
    process.exit(1);
  }
  console.log('✓ i18n-coverage: all launch languages pass every domain');
}
main().catch((err) => {
  console.error('✗ i18n-coverage: unexpected error:', err && err.message);
  process.exit(1);
});
