#!/usr/bin/env node
/**
 * scripts/split-translations.mjs
 *
 * One-shot generator: read the canonical multi-locale T object
 * from src/i18n/translations.js and emit one file per locale
 * into src/i18n/columns/T-{locale}.js. Each column file exports
 * a flat { 'dotted.key': 'value-in-that-locale' } map containing
 * only the keys with a non-blank value in that locale.
 *
 * After running this, src/i18n/translations.js is replaced by a
 * thin shim that eagerly imports T-en.js and assembles a column-
 * sparse T at boot. Other locales are lazy-loaded on setLanguage()
 * via src/i18n/columnLoader.js.
 *
 * Safety: refuses to run if translations.js already looks like
 * the generated shim, so a re-run cannot blow away real data.
 * Recover the canonical source from git history before re-running.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SRC = path.join(ROOT, 'src', 'i18n', 'translations.js');
const OUT_DIR = path.join(ROOT, 'src', 'i18n', 'columns');

const LANGS = ['en', 'fr', 'sw', 'ha', 'tw', 'hi'];

function fail(msg) {
  console.error('[split-translations] FAIL — ' + msg);
  process.exit(1);
}

if (!fs.existsSync(SRC)) fail('missing ' + SRC);

const srcText = fs.readFileSync(SRC, 'utf8');
if (srcText.includes('__GENERATED_SHIM__')) {
  fail(
    'translations.js is already the generated shim; nothing to split.\n'
    + 'To regenerate the column files from the original canonical source, '
    + 'recover the pre-shim translations.js from git history first.',
  );
}

const mod = await import(pathToFileURL(SRC).href);
const T = mod.default || mod.T || mod;
if (!T || typeof T !== 'object') fail('translations.js has no usable default export');

const allKeys = Object.keys(T);
if (allKeys.length < 100) {
  fail(
    `translations.js only exposes ${allKeys.length} keys; expected the full ~13k. `
    + 'Refusing to split what looks like an incomplete source.',
  );
}

fs.mkdirSync(OUT_DIR, { recursive: true });

const stats = {};
for (const lang of LANGS) {
  const column = {};
  let count = 0;
  for (const key of allKeys) {
    const row = T[key];
    if (!row || typeof row !== 'object') continue;
    const v = row[lang];
    if (typeof v !== 'string' || v === '') continue;
    column[key] = v;
    count += 1;
  }
  const body =
    `// AUTO-GENERATED by scripts/split-translations.mjs — do not edit by hand.\n`
    + `// Locale column: ${lang}. ${count} keys.\n`
    + `// To change a translation, edit this file directly and commit.\n`
    + `// To regenerate from a multi-locale source, restore translations.js from git.\n`
    + `\n`
    + `export default ${JSON.stringify(column, null, 2)};\n`;
  const outPath = path.join(OUT_DIR, `T-${lang}.js`);
  fs.writeFileSync(outPath, body, 'utf8');
  stats[lang] = { count, bytes: Buffer.byteLength(body, 'utf8') };
}

console.log('[split-translations] OK');
console.log(`  source rows: ${allKeys.length}`);
for (const lang of LANGS) {
  const s = stats[lang];
  console.log(
    `  T-${lang}.js: ${s.count.toString().padStart(5)} keys, `
    + `${(s.bytes / 1024).toFixed(1).padStart(7)} KB`,
  );
}
