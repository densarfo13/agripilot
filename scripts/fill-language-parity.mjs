#!/usr/bin/env node
/**
 * fill-language-parity.mjs — sprint #186 i18n parity script.
 *
 * Reads `src/i18n/columns/T-en.js` (the canonical column) and
 * appends English-value stubs for every key that's missing in each
 * non-English column. Also writes a sidecar list of pending
 * translator-review keys so humans can see the queue.
 *
 * Run with: node scripts/fill-language-parity.mjs
 *
 * Idempotent — re-running adds nothing on top of an already-aligned
 * column. Never re-orders existing keys.
 *
 * Honest behavior:
 *   - Adds missing keys with English values (same as the existing
 *     runtime fallback chain returns today).
 *   - Marks the sidecar `_translator-review-pending.json` per locale
 *     so QA + translators see exactly what to fill in.
 *   - Files retain their auto-generated header (count is updated).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const COLS_DIR = path.join(ROOT, 'src', 'i18n', 'columns');

const LOCALES = ['fr', 'sw', 'ha', 'tw', 'hi'];

async function loadColumn(code) {
  const file = path.join(COLS_DIR, `T-${code}.js`);
  const url = pathToFileURL(file).href + '?bust=' + Date.now();
  const mod = await import(url);
  return { file, data: mod.default };
}

function serializeColumn(code, data) {
  const keys = Object.keys(data);
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/split-translations.mjs — do not edit by hand.');
  lines.push(`// Locale column: ${code}. ${keys.length} keys.`);
  lines.push('// To change a translation, edit this file directly and commit.');
  lines.push('// To regenerate from a multi-locale source, restore translations.js from git.');
  lines.push('');
  lines.push('export default {');
  for (const k of keys) {
    const v = data[k];
    // Stable JSON-string escaping with double-quoted keys.
    lines.push(`  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  }
  lines.push('};');
  return lines.join('\n') + '\n';
}

async function main() {
  const { data: enData } = await loadColumn('en');
  const enKeys = Object.keys(enData);
  console.log(`[fill-parity] EN canonical column: ${enKeys.length} keys`);

  const summary = { generatedAt: new Date(0).toISOString(), perLocale: {} };

  for (const code of LOCALES) {
    const { file, data } = await loadColumn(code);
    const before = Object.keys(data).length;
    const missing = [];
    const next = { ...data };
    for (const k of enKeys) {
      if (!(k in next)) {
        next[k] = enData[k]; // English fallback stub
        missing.push(k);
      }
    }
    // Preserve order: existing keys first (in their original order),
    // then new keys appended in EN order.
    const ordered = {};
    for (const k of Object.keys(data)) ordered[k] = data[k];
    for (const k of enKeys) if (!(k in data)) ordered[k] = enData[k];

    if (missing.length === 0) {
      console.log(`[fill-parity] ${code}: OK — 0 missing (${before} keys)`);
      summary.perLocale[code] = {
        totalKeys: before,
        missingFilled: 0,
        coveragePct: 100,
        translatorReviewPending: [],
      };
      continue;
    }

    fs.writeFileSync(file, serializeColumn(code, ordered), 'utf8');
    const after = Object.keys(ordered).length;
    const pct = Math.round(((after - missing.length) / after) * 100);
    console.log(`[fill-parity] ${code}: filled ${missing.length} keys ` +
      `(${before} → ${after}); real-translation coverage ${pct}%`);
    summary.perLocale[code] = {
      totalKeys: after,
      missingFilled: missing.length,
      coveragePct: pct,
      translatorReviewPending: missing,
    };
  }

  const sidecar = path.join(COLS_DIR, '_translator-review-pending.json');
  fs.writeFileSync(sidecar, JSON.stringify(summary, null, 2), 'utf8');
  console.log(`[fill-parity] wrote sidecar: ${path.relative(ROOT, sidecar)}`);
}

main().catch((err) => {
  console.error('[fill-parity] FAIL:', err && err.stack || err);
  process.exit(1);
});
