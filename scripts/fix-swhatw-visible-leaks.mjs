function apply(file, table) {
  let src = fs.readFileSync(file, 'utf8');
  const lines = [];
  for (const [k, v] of Object.entries(table)) {
    if (src.includes('"' + k + '"')) continue;
    lines.push('  ' + JSON.stringify(k) + ': ' + JSON.stringify(v) + ',');
  }
  if (lines.length) {
    const idx = src.lastIndexOf('};');
    src = src.slice(0, idx) + '  // ── Visible-leak fix (2026-07-01): parity for the fr repair set ──\n' + lines.join('\n') + '\n' + src.slice(idx);
    fs.writeFileSync(file, src);
  }
  console.log(file + ': added ' + lines.length);
}
